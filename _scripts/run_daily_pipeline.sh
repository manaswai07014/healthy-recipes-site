#!/bin/bash
# Healthy Western Recipes — Daily Pipeline
# Runs at 08:00 HKT (00:00 UTC) to generate one new recipe
#
# Updated 2026-09-02 by 惠惠 — P4 fix:
# - REMOVED `git subtree split --prefix=. -b gh-pages-tmp` (CF Pages auto-builds from main; gh-pages not needed)
# - REMOVED `git push --force origin gh-pages-tmp:gh-pages` (would trigger Hermes DANGEROUS_PATTERNS block)
# - REMOVED `git branch -D gh-pages-tmp` (cleanup of removed branch)
# - ADDED env loading from /home/hermes/.hermes/.env (cron does not inherit shell env)
# Simplified: generate recipe → commit → push main → CF Pages auto-build → live

set -euo pipefail

# Load env (cron context has no shell env, so explicitly source from Hermes .env)
# set -a exports every subsequently-defined variable; set +a stops it.
if [ -f /home/hermes/.hermes/.env ]; then
    set -a
    source /home/hermes/.hermes/.env
    set +a
fi

PROJECT_ROOT="/home/hermes/healthy-recipes-site"
LOG_DIR="${HOME}/healthy-recipes-logs"
TIMESTAMP=$(date +%Y%m%d_%H%M%S)
LOG_FILE="${LOG_DIR}/pipeline-${TIMESTAMP}.log"

mkdir -p "${LOG_DIR}"

echo "=== Healthy Recipe Pipeline ===" | tee -a "${LOG_FILE}"
echo "Date: $(date)" | tee -a "${LOG_FILE}"
echo "Project: ${PROJECT_ROOT}" | tee -a "${LOG_FILE}"

cd "${PROJECT_ROOT}"

# Step 1/2: Generate new recipe via LLM (P45 inline atomic: markdown + image)
echo "[1/2] Generating recipe..." | tee -a "${LOG_FILE}"
/home/hermes/apps/hermes-agent/venv/bin/python3 _scripts/generate_recipe.py \
    --count 1 \
    2>&1 | tee -a "${LOG_FILE}"

# Step 1.4/2: W98 — guarantee ingredient glosses are Traditional Chinese.
# The generator prompt demands 繁體中文, but an LLM can still slip Simplified and
# 老闆's standing rule is Traditional-only. This is a *guarantee* step, not a
# dependency: it runs before the commit so the converted text ships, and every
# failure path is tolerated (`|| true`) so a missing converter can never break
# the daily recipe run.
echo "[1.4/2] Traditional-Chinese gloss guarantee..." | tee -a "${LOG_FILE}"
OCC_PY=""
for candidate in /home/hermes/.occ-venv/bin/python /tmp/occ-venv/bin/python; do
    if [ -x "${candidate}" ] && "${candidate}" -c "import opencc" 2>/dev/null; then
        OCC_PY="${candidate}"
        break
    fi
done
if [ -n "${OCC_PY}" ]; then
    "${OCC_PY}" _scripts/convert_ingredient_zh.py --apply 2>&1 | tee -a "${LOG_FILE}" || true
elif command -v uv >/dev/null 2>&1; then
    uv run --quiet --with opencc-python-reimplemented \
        python _scripts/convert_ingredient_zh.py --apply 2>&1 | tee -a "${LOG_FILE}" || true
else
    echo "  [SKIP] no opencc converter available — glosses left as generated" | tee -a "${LOG_FILE}"
fi

# Step 1.5/2: P45 Layer 2 pre-flight gate — verify ALL recipe hero_image
# paths point to real local files. If any missing, abort BEFORE git add.
# P68: Use project-local script (git tracked) instead of skill-dir script.
# Falls back to skill-dir for backwards compatibility.
echo "[1.5/2] P45 Layer 2 image asset gate..." | tee -a "${LOG_FILE}"
if [ -f "${PROJECT_ROOT}/_scripts/verify-recipe-image-assets.sh" ]; then
    bash "${PROJECT_ROOT}/_scripts/verify-recipe-image-assets.sh" \
        2>&1 | tee -a "${LOG_FILE}" || {
        echo "❌ P45 ABORT: missing hero_image assets, cron aborted before commit" | tee -a "${LOG_FILE}"
        exit 1
    }
else
    bash /home/hermes/.hermes/skills/media/healthy-recipes-site/scripts/verify-recipe-image-assets.sh \
        2>&1 | tee -a "${LOG_FILE}" || {
        echo "❌ P45 ABORT: missing hero_image assets, cron aborted before commit" | tee -a "${LOG_FILE}"
        exit 1
    }
fi

# Step 2/2: Git commit + push to main (CF Pages auto-builds from main)
echo "[2/2] Committing to git..." | tee -a "${LOG_FILE}"
cd "${PROJECT_ROOT}"

# Add only new/changed recipes + their hero images (atomic single commit, P45 + P48)
git add _recipes/*.md assets/recipes/*.jpg

# Check if there are any changes
if git diff --cached --quiet; then
    echo "No new recipes to commit (LLM dedup or quota exhaustion)" | tee -a "${LOG_FILE}"
    exit 0
fi

COMMIT_MSG="[recipe] $(date +%Y-%m-%d) — daily generated recipe

Generated by: _scripts/generate_recipe.py
LLM: ${RECIPE_LLM_MODEL:-MiniMax-M2}"

git commit -m "${COMMIT_MSG}" 2>&1 | tee -a "${LOG_FILE}"

# Push main — CF Pages watches main branch and auto-builds
# IMPORTANT: do NOT use --force; do NOT use subtree split; CF Pages needs regular main push
# W95: rebase + retry — 03:00 pipeline can race with P73 backfill push; the loser
# of the ref lock must rebase onto the winner's commit and retry instead of dying.
#
# W96 CRITICAL FIX (2026-10-21): this `git pull --rebase` ran OUTSIDE an `if`,
# so with `set -euo pipefail` any failure aborted the script BEFORE the push
# block below ever executed. The research pipeline (04:00) repeatedly left
# unstaged files in the worktree, so this pull failed every single day with
# "cannot pull with rebase: You have unstaged changes" — silently stranding
# 38 local commits and freezing the live site on 2026-09-30 for 20 days.
# Fix: autoStash the worktree changes + tolerate pull failure (`|| true`) so
# the push block ALWAYS runs.
git -c rebase.autoStash=true pull --rebase origin main 2>&1 | tee -a "${LOG_FILE}" || true
PUSH_OK=0
for attempt in 1 2 3; do
    # pipefail is set, so this pipeline's status reflects `git push`, not `tee`.
    if git push origin main 2>&1 | tee -a "${LOG_FILE}"; then
        PUSH_OK=1
        echo "[W95] push success (attempt ${attempt})" | tee -a "${LOG_FILE}"
        break
    fi
    echo "[W95] push failed (attempt ${attempt}), sleeping 30s then rebase+retry..." | tee -a "${LOG_FILE}"
    sleep 30
    git -c rebase.autoStash=true pull --rebase origin main 2>&1 | tee -a "${LOG_FILE}" || true
done
if [ "${PUSH_OK}" -ne 1 ]; then
    echo "❌ [W95] push failed after 3 attempts — local commit intact, manual push needed" | tee -a "${LOG_FILE}"
    exit 1
fi

# W96: never trust push stdout — verify remote actually received the commit (P59).
REMOTE_SHA=$(git ls-remote origin main 2>/dev/null | cut -f1)
LOCAL_SHA=$(git rev-parse HEAD)
if [ "${REMOTE_SHA}" != "${LOCAL_SHA}" ]; then
    echo "❌ [W96] push reported OK but remote (${REMOTE_SHA}) != local (${LOCAL_SHA}) — investigate" | tee -a "${LOG_FILE}"
    exit 1
fi
echo "✅ [W96] remote verified at ${LOCAL_SHA:0:7}" | tee -a "${LOG_FILE}"

echo "=== Pipeline complete — CF Pages will auto-build in ~60s ===" | tee -a "${LOG_FILE}"
